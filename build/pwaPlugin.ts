import { createHash } from 'node:crypto'
import { readdirSync, readFileSync, writeFileSync } from 'node:fs'
import { join, relative, resolve, sep } from 'node:path'
import type { Plugin } from 'vite'

const CACHEABLE = new Set(['.html', '.js', '.css', '.svg', '.png', '.webmanifest', '.ico', '.woff2'])

function walk(directory: string): string[] {
  const files: string[] = []
  for (const entry of readdirSync(directory, { withFileTypes: true })) {
    const path = join(directory, entry.name)
    if (entry.isDirectory()) files.push(...walk(path))
    else files.push(path)
  }
  return files
}

function buildServiceWorker(assets: string[], version: string): string {
  return `/* Generated by Zaiban. */
const CACHE = 'zaiban-${version}';
const PRECACHE = ${JSON.stringify(assets, null, 2)};

self.addEventListener('install', (event) => {
  event.waitUntil(
    caches.open(CACHE)
      .then((cache) => cache.addAll(PRECACHE))
      .then(() => self.skipWaiting())
  );
});

self.addEventListener('activate', (event) => {
  event.waitUntil(
    caches.keys()
      .then((keys) => Promise.all(keys.filter((key) => key !== CACHE).map((key) => caches.delete(key))))
      .then(() => self.clients.claim())
  );
});

self.addEventListener('fetch', (event) => {
  const request = event.request;
  if (request.method !== 'GET') return;

  const url = new URL(request.url);
  if (url.origin !== self.location.origin) return;

  if (request.mode === 'navigate') {
    event.respondWith(
      fetch(request).catch(() => caches.match('/index.html'))
    );
    return;
  }

  event.respondWith(
    caches.match(request).then((cached) => {
      if (cached) return cached;
      return fetch(request).then((response) => {
        if (response.ok) {
          const copy = response.clone();
          caches.open(CACHE).then((cache) => cache.put(request, copy));
        }
        return response;
      });
    })
  );
});
`
}

export function offlineAssetsPlugin(): Plugin {
  let outDirectory = ''
  return {
    name: 'zaiban-offline-assets',
    apply: 'build',
    configResolved(config) {
      outDirectory = resolve(config.root, config.build.outDir)
    },
    closeBundle() {
      if (!outDirectory) return
      const hash = createHash('sha1')
      const files = walk(outDirectory)
        .filter((file) => CACHEABLE.has(file.slice(file.lastIndexOf('.'))))
        .sort()
      for (const file of files) {
        hash.update(relative(outDirectory, file))
        hash.update(readFileSync(file))
      }
      const version = hash.digest('hex').slice(0, 10)
      const assets = files.map((file) => `/${relative(outDirectory, file).split(sep).join('/')}`)
      writeFileSync(join(outDirectory, 'sw.js'), buildServiceWorker(assets, version))
    },
  }
}
